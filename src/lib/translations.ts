export type TranslationKey = keyof (typeof translationResources)["EN"];

function formatMissingTranslation(locale: AccountLocale, key: string) {
  return `[missing translation: ${locale}.${key}]`;
}

function resolveTranslation(locale: AccountLocale, key: TranslationKey) {
  const resources: Record<string, string> = translationResources[locale];
  const translated = resources[key];

  if (translated !== undefined) {
    return translated;
  }

  const fallback = translationResources.EN[key];

  if (process.env.NODE_ENV === "development") {
    return formatMissingTranslation(locale, key);
  }

  return fallback ?? key;
}

export function getTranslations(locale: AccountLocale) {
  return (key: TranslationKey) => resolveTranslation(locale, key);
}

export function translate(locale: AccountLocale, key: TranslationKey) {
  return resolveTranslation(locale, key);
}
